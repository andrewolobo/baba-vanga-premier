-- The Stage A cache: one club's profile, keyed by a hash of the facts it was
-- written from and the prompt that wrote it. The same facts never cost a
-- second request. `dossier_hash` already folds in the club and the prompt
-- version; both are columns as well, so the cache can be read by club.
CREATE TABLE team_summaries (
    team_id         INTEGER NOT NULL REFERENCES teams(team_id),
    dossier_hash    TEXT NOT NULL,
    prompt_version  TEXT NOT NULL,
    summary         JSONB NOT NULL,
    llm_model       TEXT NOT NULL,
    input_tokens    INTEGER NOT NULL,
    output_tokens   INTEGER NOT NULL,
    created_at      TEXT NOT NULL
                    DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (team_id, dossier_hash, prompt_version)
);

-- Append-only, like `tips`. One row is one published analysis: the evidence
-- it was written from, the text the validator passed, and every request it
-- took (`attempts`: stage, try, the validator's errors, tokens), so a
-- rejection rate can be measured rather than guessed.
--
-- `status` 'ok' carries text; 'fallback' carries none, and the page draws
-- the numbers-only card from `evidence_pack` instead. Unvalidated text is
-- never stored, so it can never be served.
--
-- The two partial unique indexes are the safety property, enforced here
-- rather than in Python: per fixture and prompt version, **at most one ok
-- and at most one fallback**. A fallback can be superseded once, by a manual
-- re-run that passes. An ok is never replaced, because what a reader was
-- shown has to stay true afterwards. A second attempt at either is dropped
-- by ON CONFLICT DO NOTHING.
CREATE TABLE match_analyses (
    analysis_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fixture_id      INTEGER NOT NULL REFERENCES fixtures(fixture_id),
    tip_id          INTEGER NOT NULL REFERENCES tips(tip_id),
    prompt_version  TEXT NOT NULL,          -- the match prompt; summaries carry their own
    llm_model       TEXT NOT NULL,          -- the deployment that wrote it
    model_version   TEXT NOT NULL,          -- the artifact behind the call
    status          TEXT NOT NULL CHECK (status IN ('ok', 'fallback')),
    evidence_pack   JSONB NOT NULL,
    analysis        JSONB,
    summaries       JSONB,
    attempts        JSONB NOT NULL,
    warnings        JSONB NOT NULL,
    input_tokens    INTEGER NOT NULL,
    output_tokens   INTEGER NOT NULL,
    created_at      TEXT NOT NULL
                    DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    CHECK ((status = 'ok') = (analysis IS NOT NULL))
);

CREATE UNIQUE INDEX uq_match_analyses_ok
    ON match_analyses (fixture_id, prompt_version) WHERE status = 'ok';
CREATE UNIQUE INDEX uq_match_analyses_fallback
    ON match_analyses (fixture_id, prompt_version) WHERE status = 'fallback';
